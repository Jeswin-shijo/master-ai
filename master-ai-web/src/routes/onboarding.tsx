import { useEffect, useRef, useState } from 'react';
import { useMutation, useQueryClient } from '@tanstack/react-query';
import { RefreshCw, Sparkles } from 'lucide-react';
import { useNavigate } from 'react-router';
import type { PackDraft } from '@onehuman/schemas';
import { PackSummary } from '@/components/pack-summary';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { ErrorNote, Spinner } from '@/components/ui/feedback';
import { Input } from '@/components/ui/form';
import { api } from '@/lib/api';
import { useSession } from '@/lib/session';

/**
 * The platform adapts to the owner's industry: it matches a curated pack or
 * generates one, shows exactly what it will set up, and installs it on approval.
 */
export function OnboardingPage() {
  const tenant = useSession((s) => s.tenant);
  const setTenant = useSession((s) => s.setTenant);
  const navigate = useNavigate();
  const queryClient = useQueryClient();
  const [industry, setIndustry] = useState(tenant?.industry ?? '');
  const [sampleData, setSampleData] = useState(true);
  const [draft, setDraft] = useState<PackDraft | null>(null);

  const preview = useMutation({
    mutationFn: (opts: { industry?: string; forceGenerate?: boolean }) => api.onboarding.preview(opts),
    onSuccess: setDraft,
  });
  const install = useMutation({
    mutationFn: () => api.onboarding.install({ draftId: draft!.id, sampleData }),
    onSuccess: async () => {
      const t = await api.tenant.get();
      setTenant(t);
      await queryClient.invalidateQueries();
      navigate('/');
    },
  });

  // Draft a pack once on arrival, from the industry given at signup.
  const started = useRef(false);
  useEffect(() => {
    if (started.current) return;
    started.current = true;
    preview.mutate({});
  }, [preview]);

  return (
    <div className="mx-auto max-w-5xl px-4 py-10">
      <p className="text-sm font-medium text-primary">Step 2 of 2</p>
      <h1 className="mt-1 text-2xl font-semibold tracking-tight text-fg">Your operating system, adapted to your business</h1>
      <p className="mt-2 max-w-2xl text-sm text-fg-muted">
        Review the agents, records and approval rules set up for <span className="font-medium text-fg">{draft?.industry ?? tenant?.industry}</span>. Nothing runs until you install it, and every risky action will still need your approval.
      </p>

      <form
        className="mt-6 flex flex-wrap gap-2"
        onSubmit={(e) => {
          e.preventDefault();
          preview.mutate({ industry });
        }}
      >
        <Input value={industry} onChange={(e) => setIndustry(e.target.value)} className="max-w-md" aria-label="Industry" />
        <Button type="submit" variant="secondary" loading={preview.isPending && !preview.variables?.forceGenerate}>
          <RefreshCw /> Adapt to this
        </Button>
      </form>

      <ErrorNote error={preview.error} className="mt-4" />
      {preview.isPending && <Spinner label="Designing your industry pack…" />}

      {draft && !preview.isPending && (
        <div className="mt-8 space-y-6">
          <div className="flex flex-wrap items-start justify-between gap-4 rounded-lg border border-primary/30 bg-primary-soft px-5 py-4">
            <div className="min-w-0">
              <div className="flex flex-wrap items-center gap-2">
                <h2 className="text-lg font-semibold text-fg">{draft.pack.name}</h2>
                <Badge tone={draft.source === 'registry' ? 'success' : 'info'}>
                  {draft.generator === 'registry' ? 'Curated pack' : draft.generator === 'llm' ? 'Generated by AI' : 'Composed from building blocks'}
                </Badge>
                <Badge>v{draft.pack.version}</Badge>
              </div>
              <p className="mt-1 text-sm text-fg-muted">{draft.rationale}</p>
              <p className="mt-1 text-xs text-fg-muted">Built on: {draft.pack.lineage.join(' → ')}</p>
            </div>
            {draft.source === 'registry' && (
              <Button variant="secondary" size="sm" onClick={() => preview.mutate({ industry: draft.industry, forceGenerate: true })} loading={preview.isPending}>
                <Sparkles /> Generate a custom pack instead
              </Button>
            )}
          </div>

          <PackSummary pack={draft.pack} />

          <div className="flex flex-wrap items-center gap-4 border-t border-border pt-6">
            <label className="flex items-center gap-2 text-sm text-fg">
              <input type="checkbox" checked={sampleData} onChange={(e) => setSampleData(e.target.checked)} className="size-4 accent-[var(--oh-primary)]" />
              Add a few sample records so I can try the agents
            </label>
            <Button size="lg" className="ml-auto" onClick={() => install.mutate()} loading={install.isPending}>
              Install and open command center
            </Button>
          </div>
          <ErrorNote error={install.error} />
        </div>
      )}
    </div>
  );
}
