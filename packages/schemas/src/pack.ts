import { z } from 'zod';
import { ConditionsSchema, DueRuleSchema, SlugSchema, ToolNameSchema } from './common';
import { EscalationSetSchema, JobCardSchema, JobDefSchema, type EscalationSet, type JobCard, type JobDef } from './jobs';
export * from './common';
import { AgentClearanceSchema, DataClassSchema, ModelTierSchema } from './autonomy';
import {
  LifecycleSchema,
  PolicyWhenSchema,
  SectorIdSchema,
  type CaseCategory,
  type LifecycleRole,
  type ResolvedLifecycle,
} from './lifecycle';

/**
 * Industry Pack format. A sector is data: entities, agent roles, workflows,
 * policies, KPIs and UI hints. Keys are snake_case because packs are authored
 * as YAML (see packs/*) or generated by the LLM gateway.
 */

export const SemverSchema = z.string().regex(/^\d+\.\d+\.\d+$/, 'semantic version, e.g. 1.2.0');

export const FieldTypeSchema = z.enum([
  'string',
  'text',
  'number',
  'integer',
  'boolean',
  'date',
  'datetime',
  'email',
  'phone',
  'money',
  'enum',
  'reference',
]);
export type FieldType = z.infer<typeof FieldTypeSchema>;

export const EntityFieldSchema = z.object({
  name: z.string().regex(/^[a-z][a-zA-Z0-9_]*$/, 'camelCase field name'),
  label: z.string().min(1),
  type: FieldTypeSchema,
  required: z.boolean().default(false),
  /** Allowed values when `type` is `enum`. */
  options: z.array(z.string()).optional(),
  /** Target entity name when `type` is `reference`. */
  ref: z.string().optional(),
  description: z.string().optional(),
});
export type EntityField = z.infer<typeof EntityFieldSchema>;

export const EntityDefSchema = z.object({
  name: z.string().regex(/^[A-Z][A-Za-z0-9]*$/, 'PascalCase entity name'),
  label: z.string().min(1),
  plural_label: z.string().optional(),
  description: z.string().optional(),
  fields: z.array(EntityFieldSchema).min(1),
  /** Field shown as the record's title in lists and approvals. */
  title_field: z.string().optional(),
  /** Columns for the schema-driven table view. Defaults to the first five fields. */
  list_columns: z.array(z.string()).optional(),
});
export type EntityDef = z.infer<typeof EntityDefSchema>;

export const ModelPrefSchema = z.object({
  tier: ModelTierSchema.default('standard'),
  fallback: ModelTierSchema.optional(),
  data_class: DataClassSchema.default('internal'),
});

export const BudgetsSchema = z.object({
  tokens_per_task: z.number().int().positive().default(200_000),
  money_per_task_inr: z.number().nonnegative().default(0),
  max_steps: z.number().int().positive().max(200).default(40),
});

export const StopConditionSchema = z.enum(['goal_met', 'budget_exceeded', 'policy_blocked', 'needs_human']);

/** Agent role as declared inside a pack. */
export const PackAgentSchema = z.object({
  role: SlugSchema,
  name: z.string().min(1),
  description: z.string().min(1),
  /** Extra role instructions appended to the agent's system prompt. */
  instructions: z.string().optional(),
  autonomy: AgentClearanceSchema.default(2),
  tools: z.array(ToolNameSchema).min(1),
  model: ModelPrefSchema.prefault({}),
  budgets: BudgetsSchema.prefault({}),
  memory: z
    .object({
      episodic: z.boolean().default(true),
      knowledge: z.array(z.string()).default([]),
    })
    .prefault({}),
  stop_when: z.array(StopConditionSchema).default(['goal_met', 'budget_exceeded', 'policy_blocked', 'needs_human']),
  output_schema: z.string().optional(),
  /** The agent's job card: mission, limits and what makes it stop and ask. */
  job: JobCardSchema.optional(),
});
export type PackAgent = z.infer<typeof PackAgentSchema>;

export const ToolRiskOverrideSchema = z.object({
  external_reach: z.boolean().optional(),
  reversible: z.boolean().optional(),
  moves_money: z.boolean().optional(),
  sensitivity: DataClassSchema.optional(),
});

/**
 * Industry-specific tool built on a generic catalog primitive, e.g.
 * `booking.confirm` = `records.update` with `{ entity: Booking, patch: { status: confirmed } }`.
 */
export const ToolAliasSchema = z.object({
  name: ToolNameSchema,
  description: z.string().min(1),
  uses: ToolNameSchema,
  /** Arguments fixed by the pack; the agent cannot override them. */
  with: z.record(z.string(), z.unknown()).optional(),
  /** Minimum action level for this tool. */
  level: z.union([z.literal(1), z.literal(2), z.literal(3), z.literal(4)]).optional(),
  risk: ToolRiskOverrideSchema.optional(),
});
export type ToolAlias = z.infer<typeof ToolAliasSchema>;

export const WorkflowStepSchema = z.object({
  key: SlugSchema,
  title: z.string().min(1),
  agent: SlugSchema,
  depends_on: z.array(SlugSchema).default([]),
  instructions: z.string().min(1),
});

/** One thing a check-in asks, e.g. "How many workers were on site today?". */
export const RoutineQuestionSchema = z.object({
  key: z.string().regex(/^[a-z][a-zA-Z0-9_]*$/, 'camelCase key'),
  /** Short label for tables and reports: "Workers on site". */
  label: z.string().min(1),
  /** How the AI asks it on the phone, and the form shows it. */
  ask: z.string().min(1),
  type: z.enum(['number', 'percent', 'yes_no', 'text', 'choice']),
  options: z.array(z.string()).optional(),
  required: z.boolean().default(true),
  /** Any answer other than none / no is a problem to show the owner (shortages, blockers). */
  flag: z.boolean().default(false),
  /** Unit for numbers, e.g. "workers". */
  unit: z.string().optional(),
});
export type RoutineQuestion = z.infer<typeof RoutineQuestionSchema>;

/** A routine that adds items to a list instead of asking fixed questions, e.g. today's bills. */
export const CollectSchema = z.strictObject({
  /** The list (register id) the items go to. */
  list: SlugSchema,
  /** The fields the AI asks for, in this order. */
  ask: z.array(z.string()).min(1).max(12),
  /** Fields the AI fills itself: `today` (a date), `now` (a date-time) or a fixed value. */
  defaults: z.record(z.string(), z.union([z.string(), z.number(), z.boolean()])).default({}),
  /** Items one call takes before it asks for the rest in the app. */
  max_items: z.number().int().min(1).max(25).default(15),
  /** Who it calls, shown when the owner switches it on: "the billing clerk". */
  who: z.string().min(1).optional(),
});
export type Collect = z.infer<typeof CollectSchema>;

/** A repeating check-in the pack offers, e.g. a daily site report. The owner turns it on. */
export const RoutineTemplateSchema = z
  .object({
    id: SlugSchema,
    name: z.string().min(1),
    description: z.string().min(1),
    mode: z.enum(['manual', 'automatic']).default('automatic'),
    /** 0 = Sunday … 6 = Saturday. */
    days: z.array(z.number().int().min(0).max(6)).min(1).default([1, 2, 3, 4, 5, 6]),
    /** Local time (India), HH:MM: when the AI calls, or when manual updates are due. */
    time: z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/).default('18:00'),
    questions: z.array(RoutineQuestionSchema).max(8).default([]),
    /** Instead of questions: the items it adds to a list. */
    collect: CollectSchema.optional(),
  })
  .refine((t) => (t.questions.length > 0) !== (t.collect !== undefined), 'a routine takes either questions or collect, not both');
export type RoutineTemplate = z.infer<typeof RoutineTemplateSchema>;

export const WorkflowDefSchema = z.object({
  id: SlugSchema,
  name: z.string().min(1),
  description: z.string().min(1),
  /** Words that suggest this workflow fits a goal (used by the offline planner). */
  keywords: z.array(z.string()).default([]),
  /** Gallery category; defaults to the name of the pack that defines the workflow. */
  category: z.string().optional(),
  trigger: z.object({ event: z.string() }).optional(),
  steps: z.array(WorkflowStepSchema).min(1),
});
export type WorkflowDef = z.infer<typeof WorkflowDefSchema>;

const MoneyThresholdSchema = z.object({
  amount: z.number().nonnegative(),
  currency: z.string().length(3).default('INR'),
});

const ApprovalThresholdSchema = MoneyThresholdSchema.extend({
  /** Also ask when the amount is unknown (case gates read it from free text, so it can be missing). */
  unknown_needs_approval: z.boolean().optional(),
});

export const PolicyRuleSchema = z
  .object({
    id: SlugSchema.optional(),
    /** Tool name, or `*` for every tool. */
    action: z.union([ToolNameSchema, z.literal('*')]),
    /** Restrict the rule to one agent role. */
    agent: SlugSchema.optional(),
    require_approval: z.boolean().optional(),
    require_approval_above: ApprovalThresholdSchema.optional(),
    forbid: z.boolean().optional(),
    forbid_above: MoneyThresholdSchema.optional(),
    /** Who approves: `owner` or a role name. */
    approver: z.string().default('owner'),
    reason: z.string().optional(),
    /** Only for case gates: narrows the rule to cases in these categories, priorities, risks or sources. */
    when: PolicyWhenSchema.optional(),
  })
  .refine(
    (r) => r.require_approval || r.require_approval_above || r.forbid || r.forbid_above,
    'a policy rule needs require_approval, require_approval_above, forbid or forbid_above',
  );
export type PolicyRule = z.infer<typeof PolicyRuleSchema>;

export const KpiSourceSchema = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('records_count'),
    entity: z.string(),
    where: z.record(z.string(), z.union([z.string(), z.number(), z.boolean()])).optional(),
  }),
  z.object({
    type: z.literal('ops'),
    metric: z.enum([
      'tasks_completed',
      'approval_rejection_rate',
      'avg_approval_minutes',
      'llm_cost_inr',
      'actions_blocked',
    ]),
  }),
]);

export const KpiDefSchema = z.object({
  id: SlugSchema,
  name: z.string().min(1),
  description: z.string().min(1),
  unit: z.enum(['count', 'percent', 'minutes', 'hours', 'inr']),
  direction: z.enum(['up', 'down']),
  target: z.number().optional(),
  /** How to compute it. Without a source the KPI waits for a data connector. */
  source: KpiSourceSchema.optional(),
});
export type KpiDef = z.infer<typeof KpiDefSchema>;

/** A procedure agents follow and cite. Loaded into the company's knowledge base at install. */
export const PlaybookSchema = z.strictObject({
  id: SlugSchema,
  title: z.string().min(1),
  /** Markdown: the procedure in plain steps. */
  body: z.string().min(80),
  source: z.string().optional(),
});
export type Playbook = z.infer<typeof PlaybookSchema>;

/** On a sector base pack: an organization type people may type in, and the ready-made type it is closest to. */
export const OtherOrgTypeSchema = z.strictObject({
  name: z.string().min(1),
  keywords: z.array(z.string().min(1)).min(1),
  closest: SlugSchema,
});
export type OtherOrgType = z.infer<typeof OtherOrgTypeSchema>;

const HHMM = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, 'HH:MM');

/**
 * Where a call finds a phone number or a name: a field of the item, a field of
 * the item a reference points at, or a field of another record found by matching.
 */
export const ContactPathSchema = z.union([
  z.strictObject({ field: z.string() }),
  z.strictObject({ ref: z.string(), field: z.string() }),
  z.strictObject({ lookup: z.string(), match: z.string(), value: z.string(), field: z.string() }),
]);
export type ContactPath = z.infer<typeof ContactPathSchema>;

/** A follow-up call a list offers on its open items. Every follow-up starts off. */
export const FollowUpSchema = z
  .strictObject({
    id: SlugSchema,
    label: z.string().min(1),
    /** party: a customer, supplier or other outside party. staff: someone in the team. */
    who: z.enum(['party', 'staff']),
    /** When an item is due for a call: the same overdue or expiring rule a check uses. */
    due: DueRuleSchema,
    when: ConditionsSchema.optional(),
    phone: ContactPathSchema.optional(),
    /** The name the AI asks for before it says anything about the item. */
    contact: ContactPathSchema.optional(),
    /** Staff calls: the field holding a team member's name. */
    staff: z.strictObject({ field: z.string() }).optional(),
    /** Read out once the person is confirmed. */
    about: z.array(z.string()).min(1),
    /** What the call may propose (party) or change (staff). A promised date is always allowed. */
    find_out: z.array(z.string()).default([]),
    /** Days between calls about one item; 3 for parties and 1 for staff when unset. */
    every_days: z.number().int().min(1).max(30).optional(),
    max_tries: z.number().int().min(1).max(5).default(3),
    /** A narrower calling window, e.g. RBI's 08:00–19:00 for recovery calls. */
    hours: z.strictObject({ start: HHMM, end: HHMM }).refine((h) => h.start < h.end, { message: 'Calling hours must end after they start', path: ['end'] }).optional(),
  })
  .refine(
    (f) => (f.who === 'party' ? !!f.phone && !!f.contact && !f.staff : !!f.staff && !f.phone && !f.contact),
    'a party follow-up needs phone and contact; a staff follow-up needs staff',
  );
export type FollowUp = z.infer<typeof FollowUpSchema>;

const checkExtras = {
  /** Only check items that meet these conditions. */
  when: ConditionsSchema.optional(),
  /** The rule behind the check, added to its message: "e-way bill needed above ₹50,000". */
  why: z.string().min(1).optional(),
};

/**
 * One of the fixed kinds of check a list runs on every item. The app works
 * them out (in SQL, when a list is read), never a model.
 */
export const CheckSchema = z.union([
  z.strictObject({ missing: z.array(z.string()).min(1), ...checkExtras }),
  z.strictObject({
    adds_up: z.strictObject({
      field: z.string(),
      plus: z.array(z.string()).default([]),
      minus: z.array(z.string()).default([]),
      tolerance: z.number().nonnegative().default(1),
    }),
    ...checkExtras,
  }),
  z.strictObject({
    limit: z
      .strictObject({
        fields: z.array(z.string()).min(1),
        max: z.union([z.string(), z.number()]).optional(),
        min: z.union([z.string(), z.number()]).optional(),
        factor: z.number().positive().default(1),
      })
      .refine((l) => (l.max === undefined) !== (l.min === undefined), 'a limit needs exactly one of max or min'),
    ...checkExtras,
  }),
  z.strictObject({ duplicate: z.array(z.string()).min(1), ...checkExtras }),
  z.strictObject({ overdue: z.strictObject({ date: z.string(), grace_days: z.number().int().nonnegative().default(0) }), ...checkExtras }),
  z.strictObject({ expiring: z.strictObject({ date: z.string(), days: z.number().int().positive() }), ...checkExtras }),
]);
export type Check = z.infer<typeof CheckSchema>;

/** A list the head of the organization sees: one record type, with its columns, filters, totals and checks. */
export const RegisterSchema = z.strictObject({
  id: SlugSchema,
  entity: z.string(),
  label: z.string().min(1).optional(),
  /** A card on the Lists page; false lists it under "Other lists". */
  main: z.boolean().default(true),
  columns: z.array(z.string()).min(1).optional(),
  filters: z.array(z.string()).optional(),
  /** The date the list's date range filters on. */
  date_field: z.string().optional(),
  sort: z.strictObject({ field: z.string(), dir: z.enum(['asc', 'desc']).default('desc') }).optional(),
  totals: z.array(z.string()).optional(),
  card: z
    .strictObject({
      count: z.strictObject({ when: ConditionsSchema.optional(), label: z.string().min(1) }).optional(),
      sum: z.strictObject({ field: z.string(), when: ConditionsSchema.optional(), label: z.string().min(1) }).optional(),
    })
    .optional(),
  checks: z.array(CheckSchema).default([]),
  /** Calls the AI can make about open items, each off until switched on. */
  follow_ups: z.array(FollowUpSchema).optional(),
});
export type Register = z.infer<typeof RegisterSchema>;

export const PackSchema = z.object({
  id: SlugSchema,
  version: SemverSchema,
  name: z.string().min(1),
  description: z.string().min(1),
  kind: z.enum(['base', 'industry']).default('industry'),
  /** Sector this pack belongs to (inherited when unset). */
  sector: SectorIdSchema.optional(),
  /** The 8-stage case lifecycle, partial; merged down the `extends` chain. */
  lifecycle: LifecycleSchema.optional(),
  /** Words used to match an owner's free-text industry to this pack. */
  match: z
    .object({
      keywords: z.array(z.string()).default([]),
      /** Words that rule this pack out, e.g. "veterinary" for a human hospital. */
      exclude: z.array(z.string()).default([]),
    })
    .optional(),
  extends: z.array(SlugSchema).default([]),
  /** Term overrides, e.g. `{ Customer: Patient }`, applied to entity labels. */
  labels: z.record(z.string(), z.string()).default({}),
  entities: z.array(EntityDefSchema).default([]),
  agents: z.array(PackAgentSchema).default([]),
  tools: z.array(ToolAliasSchema).default([]),
  workflows: z.array(WorkflowDefSchema).default([]),
  /** Repeating check-ins the business can switch on, e.g. a daily site report by phone. */
  routines: z.array(RoutineTemplateSchema).default([]),
  /** The lists the head sees, over the pack's entities. Every entity without one gets a default list. */
  registers: z.array(RegisterSchema).default([]),
  policies: z.array(PolicyRuleSchema).default([]),
  kpis: z.array(KpiDefSchema).default([]),
  /** Integrations the sector needs (booking engines, ERP, EHR...). */
  connectors: z.array(z.string()).default([]),
  /** Words that make an agent stop and hand over to a person, shared by every agent in the pack. */
  escalations: z.array(EscalationSetSchema).default([]),
  /** Scripted jobs: read, ask the AI, check, act. */
  jobs: z.array(JobDefSchema).default([]),
  /** Procedures for the company's knowledge base (permit-to-work, KYC, triage...). */
  playbooks: z.array(PlaybookSchema).default([]),
  /** Sector base packs only: typed-in organization types and the ready-made type each borrows offline. */
  other_org_types: z.array(OtherOrgTypeSchema).default([]),
});
export type Pack = z.infer<typeof PackSchema>;
export type PackInput = z.input<typeof PackSchema>;

/** A pack with `extends` flattened. This is what a workspace runs. */
export type ResolvedPack = Omit<Pack, 'lifecycle'> & {
  /** Pack ids from the most basic ancestor to this pack. */
  lineage: string[];
  source: PackSource;
  /** Missing on workspaces installed before lifecycles existed; read it with `lifecycleOf()`. */
  lifecycle?: ResolvedLifecycle;
};

export type PackSource = 'registry' | 'generated' | 'forked';

/** What the current base packs add to an installed workspace. Additions only. */
export interface PackUpdates {
  agents: Pack['agents'];
  tools: Pack['tools'];
  workflows: Pack['workflows'];
  routines: Pack['routines'];
  policies: Pack['policies'];
  kpis: Pack['kpis'];
  /** Playbooks the workspace doesn't have yet; they go into Knowledge. */
  playbooks: Playbook[];
  /** Record types the workspace doesn't have yet. */
  entities: EntityDef[];
  /** New optional fields on record types it has. A required field is never added: items saved before would stop validating. */
  fields: { entity: string; fields: EntityField[] }[];
  /** Lists it doesn't have yet, each valid against the updated record types. */
  registers: Register[];
  /** New follow-ups on lists the workspace already has. */
  followUps?: { register: string; followUps: FollowUp[] }[];
  /** Escalation sets the workspace doesn't have yet. */
  escalations?: EscalationSet[];
  /** Jobs the workspace doesn't have yet. */
  jobs?: JobDef[];
  /** Job cards for agents that have none. */
  jobCards?: { role: string; job: JobCard }[];
  /** The whole lifecycle for workspaces installed before lifecycles, otherwise new categories and roles. */
  lifecycle: { whole: ResolvedLifecycle | null; categories: CaseCategory[]; roles: LifecycleRole[] };
}
